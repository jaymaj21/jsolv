package org.jsolv.generator;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.util.*;
import javax.lang.model.SourceVersion;

/** Dependency-free generation, shared by the Maven goal and its tests. */
public final class LabelGenerator {
    private static final String HEADER = "// Generated by jsolv-maven-plugin. Do not edit.\n";
    private LabelGenerator() {}

    public static int generate(Path config, Path output) throws IOException {
        Properties properties = new Properties() {
            @Override public synchronized Object put(Object key, Object value) {
                if (containsKey(key)) throw new IllegalArgumentException("Duplicate config key: " + key);
                return super.put(key, value);
            }
        };
        try (var reader = Files.newBufferedReader(config, StandardCharsets.UTF_8)) {
            properties.load(reader);
        }
        for (String key : properties.stringPropertyNames()) {
            if (!Set.of("package", "labels").contains(key))
                throw new IllegalArgumentException("Unknown config key: " + key);
        }
        String packageName = properties.getProperty("package", "").trim();
        if (packageName.isEmpty()) throw new IllegalArgumentException("Missing package");
        for (String part : packageName.split("\\.", -1)) validateName(part);
        String labelsText = properties.getProperty("labels", "").trim();
        if (labelsText.isEmpty()) throw new IllegalArgumentException("Missing labels");
        Set<String> labels = new TreeSet<>();
        for (String item : labelsText.split(",", -1)) {
            String label = item.trim();
            validateName(label);
            if (!labels.add(label)) throw new IllegalArgumentException("Duplicate label: " + label);
        }
        // Validate the entire configuration before touching previous output.
        Path root = output.toAbsolutePath().normalize();
        Files.createDirectories(root);
        Map<Path, String> desired = new HashMap<>();
        for (String label : labels) {
            Path file = root.resolve(packageName.replace('.', '/')).resolve(label + ".java");
            String source = HEADER + "package " + packageName + ";\n\n"
                + "@org.jsolv.StaticTag\n"
                + "@java.lang.annotation.Target({java.lang.annotation.ElementType.TYPE_USE, java.lang.annotation.ElementType.PARAMETER, java.lang.annotation.ElementType.METHOD})\n"
                + "@java.lang.annotation.Retention(java.lang.annotation.RetentionPolicy.CLASS)\n"
                + "public @interface " + label + " {}\n";
            desired.put(file, source);
        }
        for (var entry : desired.entrySet()) {
            Path file = entry.getKey();
            if (Files.exists(file) && !Files.readString(file).startsWith(HEADER))
                throw new IllegalArgumentException("Refusing to overwrite non-generated file: " + file);
        }
        // Only remove obsolete sources bearing our ownership header; never recurse-delete a directory.
        try (var files = Files.walk(root)) {
            for (Path file : files.filter(p -> Files.isRegularFile(p) && p.toString().endsWith(".java")).toList()) {
                if (!desired.containsKey(file) && Files.readString(file).startsWith(HEADER)) Files.delete(file);
            }
        }
        for (var entry : desired.entrySet()) {
            Files.createDirectories(entry.getKey().getParent());
            if (!Files.exists(entry.getKey()) || !Files.readString(entry.getKey()).equals(entry.getValue()))
                Files.writeString(entry.getKey(), entry.getValue(), StandardCharsets.UTF_8);
        }
        return labels.size();
    }

    private static void validateName(String name) {
        if (!SourceVersion.isIdentifier(name) || SourceVersion.isKeyword(name, SourceVersion.RELEASE_17)
                || Set.of("var", "yield", "record", "sealed", "permits").contains(name))
            throw new IllegalArgumentException("Invalid Java name: " + name);
    }
}
